COST_CONCEPT = [
    "成本有广义和狭义之分。广义成本泛指企业为达到一定目的而发生的各种耗费；",
    "狭义成本通常指产品成本，即企业为生产一定种类、一定数量的产品所发生的生产费用。",
    "在成本会计中，成本是对象化的费用：先归集生产经营过程中的各项耗费，再按成本计算对象进行分配和归集。",
    "产品成本包括直接材料、直接人工和制造费用等生产费用；期间费用包括销售费用、管理费用和财务费用，",
    "期间费用不计入产品生产成本，而是直接计入当期损益。",
    "成本的作用：①补偿生产耗费的尺度；②综合反映企业工作质量；③制定产品价格的重要依据；",
    "④进行经营决策的重要工具；⑤评价企业经济效益的重要指标。",
]

